#!/usr/bin/env python3
"""Generate the canonical ShouTech repository file and folder index."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "FILE_INDEX.md"
SKIP = {".git", ".vs", ".idea", ".cache", ".venv", "venv", "bin", "obj", "build", "dist", "publish", "artifacts", "coverage", "TestResults", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".tox", "node_modules", "packages"}
PURPOSE = {
    "app": "WPF desktop UI, views, view models, services, navigation, localization and resources",
    "src": "Domain, application, infrastructure and inventory libraries",
    "dba": "Database definitions and provider-specific migration history",
    "svc": "Independent Windows background service",
    "tools": "Migration CLI and developer verification harnesses",
    "tests": "Automated regression and integration tests",
    "sec": "Native security library and native tests",
    "cfg": "Non-secret application defaults",
    "docs": "Architecture, product, engineering and user documentation",
    "archive": "Historical schema snapshots and legacy reference material",
    ".github": "CI workflows and repository automation",
}

def validate_layout() -> None:
    required = (
        ROOT / "ShouTech.ERP.csproj",
        ROOT / "ShouTech.sln",
        ROOT / "App.xaml",
        ROOT / "App.xaml.cs",
    )
    missing = [path.relative_to(ROOT).as_posix() for path in required if not path.is_file()]
    if missing:
        raise SystemExit("Canonical root entry-point files are missing: " + ", ".join(missing))

    app_definitions = sorted(
        path.relative_to(ROOT).as_posix()
        for path in ROOT.rglob("App.xaml")
        if not any(part in SKIP for part in path.relative_to(ROOT).parts)
    )
    if app_definitions != ["App.xaml"]:
        raise SystemExit("Expected exactly one WPF application definition at App.xaml; found: " +
                         (", ".join(app_definitions) or "(none)"))

    forbidden = (
        ROOT / "ShouTech.ERP.Com",
        ROOT / "cod",
        ROOT / "src" / "Domain",
        ROOT / "src" / "ShouTech.Domain",
    )
    present = [path.relative_to(ROOT).as_posix() for path in forbidden if path.exists()]
    if present:
        raise SystemExit("Legacy repository wrappers must not be reintroduced: " + ", ".join(present))


def main() -> None:
    validate_layout()
    files: list[str] = []
    dirs: set[str] = set()
    for path in ROOT.rglob("*"):
        rel = path.relative_to(ROOT)
        if any(part in SKIP for part in rel.parts):
            continue
        if path.is_dir():
            dirs.add(rel.as_posix())
        elif path.is_file():
            files.append(rel.as_posix())
            dirs.update(parent.as_posix() for parent in rel.parents if parent.as_posix() != ".")

    lines = [
        "# ShouTech ERP — File and Folder Index", "",
        "Generated by `tools/gen_index.py`. Regenerate after structural changes.", "",
        f"- Directories: {len(dirs)}", f"- Files: {len(files)}", "",
        "## Directory index", "",
        "| Directory | Responsibility |", "|---|---|",
    ]
    for folder in sorted(dirs, key=str.casefold):
        area = PURPOSE.get(folder.split("/", 1)[0], "Module-owned source, resource, or support files")
        lines.append(f"| `{folder}/` | {area} |")
    lines += ["", "## File index", "", "| File | Area |", "|---|---|"]
    for file in sorted(files, key=str.casefold):
        area = PURPOSE.get(file.split("/", 1)[0], "Repository root and build metadata")
        lines.append(f"| `{file}` | {area} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Indexed {len(dirs)} folders and {len(files)} files: {OUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
