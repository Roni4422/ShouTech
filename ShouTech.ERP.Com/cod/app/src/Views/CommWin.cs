/// <summary>
/// Sales commission console (owner sales spec Phase 09, migration 097,
/// workstream W7b): the one window for the whole commission pillar —
///   * Policies: rate definitions (Sales / Collection / Profit basis,
///     rep / material / group / customer / territory scopes, validity
///     window, tier slabs edited as "from = rate" lines);
///   * Entries: the generated commission rows with period / rep /
///     status filters — this grid IS the rep performance view for this
///     phase (RepMovementWin / TargetsRptWin stay untouched) — plus the
///     collection-basis period run and Approve / Reject;
///   * Settlements: per-rep period settlements (Create from Approved
///     entries, Approve, Pay via journal voucher).
/// Entries are generated by the posting hooks (chain: OrderService;
/// native: InvoiceWin) and by the collection period run here; this
/// window never invents amounts. RBAC: SALES.COMMISSION.VIEW gates the
/// window, MANAGE the policy/settlement edits, APPROVE the approvals,
/// PAY the payment.
/// </summary>
public sealed class CommWin : BaseWin
