    private async void OnLoaded(object sender, RoutedEventArgs e)
    {
        if (!AppHost.Permissions.Has(PermCat.Sales.CommissionView))
        {
            MessageBox.Show(this, T("Comm.PermissionDenied"), Title, MessageBoxButton.OK, MessageBoxImage.Warning);
            Close();
            return;
        }
        await RefreshAllAsync();
    }

    private void BuildUi()
    {
        var root = new DockPanel { Margin = new Thickness(12) };

        var statusBorder = new Border
        {
            Child = _statusBar,
            Padding = new Thickness(2, 5, 2, 0),
            BorderThickness = new Thickness(0, 1, 0, 0)
        };
        statusBorder.SetResourceReference(Border.BorderBrushProperty, "BorderBrush");
        DockPanel.SetDock(statusBorder, Dock.Bottom);
        root.Children.Add(statusBorder);

        var bar = new StackPanel { Orientation = Orientation.Horizontal, HorizontalAlignment = HorizontalAlignment.Right };
        StyleButton(_closeButton, "Common.Close");
        _closeButton.Click += (_, _) => Close();
        bar.Children.Add(_closeButton);
        var barBorder = new Border
        {
            Child = bar,
            Padding = new Thickness(0, 8, 0, 0),
            Margin = new Thickness(0, 8, 0, 0),
            BorderThickness = new Thickness(0, 1, 0, 0)
        };
        barBorder.SetResourceReference(Border.BorderBrushProperty, "BorderBrush");
        DockPanel.SetDock(barBorder, Dock.Bottom);
        root.Children.Add(barBorder);

        _policiesTab.Content = BuildPoliciesTab();
        _entriesTab.Content = BuildEntriesTab();
        _settlementsTab.Content = BuildSettlementsTab();
        _tabs.Items.Add(_policiesTab);
        _tabs.Items.Add(_entriesTab);
        _tabs.Items.Add(_settlementsTab);
        root.Children.Add(_tabs);

        Content = root;
        ApplyLocalizedText();
    }

