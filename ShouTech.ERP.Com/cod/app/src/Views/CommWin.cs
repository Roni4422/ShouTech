    private async Task CreateSettlementAsync()
    {
        try
        {
            if (_service is null) throw new InvalidOperationException(T("Comm.ServiceUnavailable"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionManage))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            var rep = NullIfBlank(_settlementRep.Text) ?? throw new InvalidOperationException(T("Comm.RepRequired"));
            var from = DateText(_settlementFrom) ?? throw new InvalidOperationException(T("Comm.PeriodRequired"));
            var to = DateText(_settlementTo) ?? throw new InvalidOperationException(T("Comm.PeriodRequired"));
            var settlement = await _service.CreateSettlementAsync(CurrentCompanyCode, rep, from, to, CurrentUserId);
            _statusBar.Text = Tf("Comm.SettlementCreated", settlement.EntryCount, settlement.TotalAmount);
            await RefreshSettlementsAsync();
            await RefreshEntriesAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.CreateSettlementAsync"); }
    }

    private async Task ApproveSettlementAsync()
    {
        try
        {
            if (_service is null || _settlementGrid.SelectedItem is not CommSettlement settlement)
                throw new InvalidOperationException(T("Comm.SelectSettlement"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionApprove))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            await _service.ApproveSettlementAsync(CurrentCompanyCode, settlement.Id, CurrentUserId);
            await RefreshSettlementsAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.ApproveSettlementAsync"); }
    }

    private async Task PaySettlementAsync()
    {
        try
        {
            if (_service is null || _settlementGrid.SelectedItem is not CommSettlement settlement)
                throw new InvalidOperationException(T("Comm.SelectSettlement"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionPay))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            var journalRef = await _service.PaySettlementAsync(CurrentCompanyCode, settlement.Id, CurrentUserId);
            _statusBar.Text = Tf("Comm.SettlementPaid", journalRef);
            await RefreshSettlementsAsync();
            await RefreshEntriesAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.PaySettlementAsync"); }
    }

