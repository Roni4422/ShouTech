    private void OnPolicySelected()
    {
        if (_policyGrid.SelectedItem is not CommPolicy policy) return;
        _selectedPolicyId = policy.Id;
        _policyName.Text = policy.Name;
        _policyBasis.SelectedItem = policy.Basis;
        _policyRate.Text = policy.RatePct.ToString(CultureInfo.InvariantCulture);
        _repScope.SelectedItem = policy.RepScope;
        _repCode.Text = policy.RepCode ?? string.Empty;
        _productScope.SelectedItem = policy.ProductScope;
        _materialId.Text = policy.MaterialId?.ToString(CultureInfo.InvariantCulture) ?? string.Empty;
        _groupCode.Text = policy.MaterialGroupCode ?? string.Empty;
        _customerScope.SelectedItem = policy.CustomerScope;
        _partyId.Text = policy.PartyId?.ToString(CultureInfo.InvariantCulture) ?? string.Empty;
        _areaCode.Text = policy.AreaCode ?? string.Empty;
        _validFrom.SelectedDate = ParseDate(policy.ValidFrom);
        _validTo.SelectedDate = ParseDate(policy.ValidTo);
        _policyActive.IsChecked = policy.IsActive;
        _tiers.Text = string.Join(Environment.NewLine,
            policy.Tiers.OrderBy(t => t.FromAmount).Select(t =>
                $"{t.FromAmount.ToString(CultureInfo.InvariantCulture)} = {t.RatePct.ToString(CultureInfo.InvariantCulture)}"));
    }

    private void ClearPolicyEditor()
    {
        _selectedPolicyId = null;
        _policyGrid.SelectedItem = null;
        _policyName.Text = string.Empty;
        _policyBasis.SelectedItem = CommBases.Sales;
        _policyRate.Text = "0";
        _repScope.SelectedItem = CommRepScopes.All;
        _repCode.Text = string.Empty;
        _productScope.SelectedItem = CommProductScopes.All;
        _materialId.Text = string.Empty;
        _groupCode.Text = string.Empty;
        _customerScope.SelectedItem = CommCustomerScopes.All;
        _partyId.Text = string.Empty;
        _areaCode.Text = string.Empty;
        _validFrom.SelectedDate = null;
        _validTo.SelectedDate = null;
        _policyActive.IsChecked = true;
        _tiers.Text = string.Empty;
    }

    private async Task SavePolicyAsync()
    {
        try
        {
            if (_service is null) throw new InvalidOperationException(T("Comm.ServiceUnavailable"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionManage))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            var existing = _selectedPolicyId is Guid id ? _policies.FirstOrDefault(p => p.Id == id) : null;
            var policy = existing ?? new CommPolicy();
            policy.Name = _policyName.Text.Trim();
            policy.Basis = _policyBasis.SelectedItem as string ?? CommBases.Sales;
            policy.RatePct = ParseDecimal(_policyRate.Text);
            policy.RepScope = _repScope.SelectedItem as string ?? CommRepScopes.All;
            policy.RepCode = NullIfBlank(_repCode.Text);
            policy.ProductScope = _productScope.SelectedItem as string ?? CommProductScopes.All;
            policy.MaterialId = ParseLongOrNull(_materialId.Text);
            policy.MaterialGroupCode = NullIfBlank(_groupCode.Text);
            policy.CustomerScope = _customerScope.SelectedItem as string ?? CommCustomerScopes.All;
            policy.PartyId = ParseLongOrNull(_partyId.Text);
            policy.AreaCode = NullIfBlank(_areaCode.Text);
            policy.ValidFrom = DateText(_validFrom);
            policy.ValidTo = DateText(_validTo);
            policy.IsActive = _policyActive.IsChecked == true;
            policy.Tiers = ParseTiers(policy.Id);
            await _service.SavePolicyAsync(CurrentCompanyCode, policy, CurrentUserId);
            _selectedPolicyId = policy.Id;
            _statusBar.Text = T("Comm.PolicySaved");
            await RefreshPoliciesAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.SavePolicyAsync"); }
    }

    private async Task DeletePolicyAsync()
    {
        try
        {
            if (_service is null || _selectedPolicyId is not Guid id)
                throw new InvalidOperationException(T("Comm.SelectPolicy"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionManage))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            await _service.DeletePolicyAsync(CurrentCompanyCode, id, CurrentUserId);
            ClearPolicyEditor();
            await RefreshPoliciesAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.DeletePolicyAsync"); }
    }

    private List<CommPolicyTier> ParseTiers(Guid policyId)
    {
        var tiers = new List<CommPolicyTier>();
        foreach (var rawLine in _tiers.Text.Split(NewLineSeparators, StringSplitOptions.RemoveEmptyEntries))
        {
            var parts = rawLine.Split('=');
            if (parts.Length != 2)
                throw new InvalidOperationException(Tf("Comm.TierLineInvalid", rawLine));
            tiers.Add(new CommPolicyTier
            {
                PolicyId = policyId,
                FromAmount = ParseDecimal(parts[0].Trim()),
                RatePct = ParseDecimal(parts[1].Trim())
            });
        }
        return tiers;
    }

