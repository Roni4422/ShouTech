    protected override void ApplyLocalizedText()
    {
        Title = T("Comm.Title");
        _policiesTab.Header = T("Comm.Policies");
        _entriesTab.Header = T("Comm.Entries");
        _settlementsTab.Header = T("Comm.Settlements");
        foreach (var (label, key) in _labels)
            label.Text = T(key);
        foreach (var (column, key) in _headers)
            column.Header = T(key);
        foreach (var b in new[]
        {
            _closeButton, _policyNew, _policySave, _policyDelete,
            _entryRefresh, _entryGenerate, _entryApprove, _entryReject,
            _settlementCreate, _settlementApprove, _settlementPay, _settlementRefresh
        })
            if (b.Tag is string key)
                b.Content = T(key);
    }

