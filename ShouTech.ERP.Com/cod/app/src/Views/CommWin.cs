    private async Task GenerateCollectionAsync()
    {
        try
        {
            if (_service is null) throw new InvalidOperationException(T("Comm.ServiceUnavailable"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionManage))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            var from = DateText(_entryFrom) ?? throw new InvalidOperationException(T("Comm.PeriodRequired"));
            var to = DateText(_entryTo) ?? throw new InvalidOperationException(T("Comm.PeriodRequired"));
            var created = await _service.GenerateCollectionForPeriodAsync(CurrentCompanyCode, from, to, CurrentUserId);
            _statusBar.Text = Tf("Comm.GeneratedStatus", created);
            await RefreshEntriesAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.GenerateCollectionAsync"); }
    }

    private async Task SetSelectedEntriesAsync(bool approve)
    {
        try
        {
            if (_service is null) throw new InvalidOperationException(T("Comm.ServiceUnavailable"));
            if (!AppHost.Permissions.Has(PermCat.Sales.CommissionApprove))
                throw new InvalidOperationException(T("Comm.PermissionDenied"));
            var ids = _entryGrid.SelectedItems.OfType<CommEntry>().Select(e => e.Id).ToList();
            if (ids.Count == 0) throw new InvalidOperationException(T("Comm.SelectEntries"));
            if (approve)
                await _service.ApproveEntriesAsync(CurrentCompanyCode, ids, CurrentUserId);
            else
                await _service.RejectEntriesAsync(CurrentCompanyCode, ids, CurrentUserId);
            await RefreshEntriesAsync();
        }
        catch (Exception ex) { Report(ex, "CommWin.SetSelectedEntriesAsync"); }
    }

