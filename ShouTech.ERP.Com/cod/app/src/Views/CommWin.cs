    private async Task RefreshAllAsync()
    {
        await RefreshPoliciesAsync();
        await RefreshEntriesAsync();
        await RefreshSettlementsAsync();
    }

    private async Task RefreshPoliciesAsync()
    {
        try
        {
            if (_service is null) { _statusBar.Text = T("Comm.ServiceUnavailable"); return; }
            var rows = await _service.GetPoliciesAsync(CurrentCompanyCode);
            _policies.Clear();
            _policies.AddRange(rows);
            _policyGrid.ItemsSource = null;
            _policyGrid.ItemsSource = _policies;
            _statusBar.Text = Tf("Comm.PoliciesStatus", _policies.Count);
        }
        catch (Exception ex) { Report(ex, "CommWin.RefreshPoliciesAsync"); }
    }

    private async Task RefreshEntriesAsync()
    {
        try
        {
            if (_service is null) { _statusBar.Text = T("Comm.ServiceUnavailable"); return; }
            var rows = await _service.GetEntriesAsync(CurrentCompanyCode,
                NullIfBlank(_entryRep.Text), NullIfBlank(_entryStatus.SelectedItem as string),
                DateText(_entryFrom), DateText(_entryTo));
            _entries.Clear();
            _entries.AddRange(rows);
            _entryGrid.ItemsSource = null;
            _entryGrid.ItemsSource = _entries;
            _statusBar.Text = Tf("Comm.EntriesStatus", _entries.Count, _entries.Sum(e => e.CommissionAmount));
        }
        catch (Exception ex) { Report(ex, "CommWin.RefreshEntriesAsync"); }
    }

    private async Task RefreshSettlementsAsync()
    {
        try
        {
            if (_service is null) { _statusBar.Text = T("Comm.ServiceUnavailable"); return; }
            var rows = await _service.GetSettlementsAsync(CurrentCompanyCode, NullIfBlank(_settlementRep.Text));
            _settlements.Clear();
            _settlements.AddRange(rows);
            _settlementGrid.ItemsSource = null;
            _settlementGrid.ItemsSource = _settlements;
        }
        catch (Exception ex) { Report(ex, "CommWin.RefreshSettlementsAsync"); }
    }

