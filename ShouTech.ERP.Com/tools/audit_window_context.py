#!/usr/bin/env python3
"""
ShouTech ERP - window shell-context audit.

Enumerates every window class in cod/app/src/Views and reports, per window:
  * base class,
  * direction (RTL/LTR) source,
  * company-context source,
  * theme/accent source,
and scans all XAML/code for FlowDirection pins, failing if any WINDOW-LEVEL
LeftToRight pin remains (control-level pins for direction-neutral content
such as numeric/code fields are reported, not failed).

Usage:
    python3 tools/audit_window_context.py [--write-doc]

With --write-doc, (re)generates docs/WINDOW_CONTEXT_AUDIT.md.
Exit code is non-zero when a window-level LTR pin is found.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "cod" / "app" / "src"
VIEWS = SRC / "Views"

APPHOST_SVC = re.compile(r"AppHost\.(Journal|JournalStore|Projects|Assets|Reconciliation|AccountingStructure|DatabaseHealth|Budgets|Quality)\b")
CLASS_RE = re.compile(
    r"public\s+(?:partial\s+)?(?:sealed\s+)?class\s+(\w+)\s*:\s*([\w\.]+)")


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig", errors="ignore")


def window_classes():
    """Yield (name, base, file, source) for each unique Window-derived class."""
    seen = {}
    for pattern in ("*.xaml.cs", "*.cs"):
        for f in sorted(VIEWS.rglob(pattern)):
            src = read(f)
            for m in CLASS_RE.finditer(src):
                name, base = m.group(1), m.group(2)
                if not any(k in base for k in ("Window", "BaseWin")):
                    continue
                if name in seen:
                    continue
                seen[name] = (name, base, f, src)
    return [seen[k] for k in sorted(seen)]


def direction_source(name, base):
    if "BaseWin" in base:
        return "central — BaseWin + App class handler -> ShellContext.ApplyToWindow"
    extra = {
        "MWin": " + own ApplyUiDirection (same LangDirSv source)",
        "LogWin": " + own language-change hook (LangDirSv.ApplyToWindow)",
        "Lang": " (language picker: previews the candidate language, by design)",
        "SplWin": " + own ApplyLocalization -> LangDirSv.ApplyToWindow",
        "PrmWin": " + own OnLoaded (UiLoczr + LangDirSv)",
    }.get(name, "")
    return "central — App class handler -> ShellContext.ApplyToWindow" + extra


def company_source(src):
    if APPHOST_SVC.search(src):
        return ("AppHost service (Journal/Projects/Assets/Reconciliation/Budgets) — "
                "connection-bound, REBOUND on company switch by "
                "AppHost.RebindDatabaseContext")
    if "GetConnectionString()" in src:
        return "per-call DatabaseRuntime.GetConnectionString() — current company at use time"
    if "AppState.CurrentCompanyCode" in src or "CurrentCompanyCode" in src:
        return "AppState.CurrentCompanyCode read at use time + per-call services"
    return "no direct data access in the window file — delegates to services/ViewModels that resolve per call"


def theme_source(name, src):
    snap = "ResolveBrushResource" in src or "ResolveColorResource" in src
    if name == "SplWin":
        return "custom splash artwork (by design); direction central"
    if snap:
        return ("central — app-level VisuId resources; code-resolved brush "
                "SNAPSHOTS keep the open-time accent until the window reopens")
    return "central — DynamicResource against app-level VisuId resources (live accent/theme)"


def pin_scan():
    """Return (window_level_pins, control_level_pins) as lists of strings."""
    window_pins, control_pins = [], []
    for f in sorted(SRC.rglob("*.xaml")):
        for i, line in enumerate(read(f).splitlines(), 1):
            if 'FlowDirection="LeftToRight"' in line or 'FlowDirection="RightToLeft"' in line:
                entry = f"{f.relative_to(ROOT)}:{i}: {line.strip()[:110]}"
                if re.search(r"<\w*Window[\s>]", line) or "PARTIAL-WINDOW" in line:
                    window_pins.append(entry)
                else:
                    control_pins.append(entry)
    for f in sorted(SRC.rglob("*.cs")):
        for i, line in enumerate(read(f).splitlines(), 1):
            if re.search(r"(this|window|win)\.FlowDirection\s*=\s*FlowDirection\.LeftToRight", line):
                window_pins.append(f"{f.relative_to(ROOT)}:{i}: {line.strip()[:110]}")
    return window_pins, control_pins


def main():
    rows = []
    for name, base, f, src in window_classes():
        rows.append((name, base, direction_source(name, base),
                     company_source(src), theme_source(name, src)))
    window_pins, control_pins = pin_scan()

    out = []
    out.append("# Window shell-context audit")
    out.append("")
    out.append("Generated by `tools/audit_window_context.py`. One row per window class.")
    out.append("Central routine: `ShellContext.ApplyToWindow` (Services/ShellContext.cs),")
    out.append("invoked for every window by the App-level Window.Loaded class handler and")
    out.append("by BaseWin; all values are resolved at open time from the central holders")
    out.append("(language/direction: LangDirSv/LocSvc + UsrPref.Lang; company: AppState +")
    out.append("AppHost.RebindDatabaseContext; theme/accent: UsrPref.Theme/AccentColor via")
    out.append("VisuId app resources; currency/formats: UsrPref; user/session: AppHost).")
    out.append("")
    out.append("| Window | Base | Direction source | Company source | Theme/accent source |")
    out.append("|---|---|---|---|---|")
    for name, base, d, c, t in rows:
        out.append(f"| {name} | {base} | {d} | {c} | {t} |")
    out.append("")
    out.append(f"Window classes audited: {len(rows)}")
    out.append(f"Window-level FlowDirection pins remaining: {len(window_pins)}")
    for p in window_pins:
        out.append(f"  WINDOW PIN: {p}")
    out.append(f"Control-level FlowDirection pins (direction-neutral content, justified): {len(control_pins)}")
    for p in control_pins:
        out.append(f"  control pin: {p}")
    out.append("")
    out.append("Notes:")
    out.append("- Localized STRINGS: BaseWin windows re-localize live on language change;")
    out.append("  Window-derived dialogs that build strings once (e.g. SplWin, Lang) show the")
    out.append("  language that was active when they were constructed — they are transient")
    out.append("  startup dialogs; direction and theme still update centrally.")
    out.append("- Theme: the app ships a Light theme dictionary (app-level). UsrPref.Theme")
    out.append("  accepts Light/Dark but no Dark dictionary exists yet — pre-existing gap,")
    out.append("  unrelated to context propagation.")
    out.append("- Company switching closes secondary windows (ComWin flow) and rebinds the")
    out.append("  connection-bound AppHost services, so a window opened after a switch can")
    out.append("  only ever see the new company's database.")

    text = "\n".join(out) + "\n"
    print(text)
    if "--write-doc" in sys.argv:
        (ROOT / "docs" / "WINDOW_CONTEXT_AUDIT.md").write_text(text, encoding="utf-8")
        print(f"[wrote docs/WINDOW_CONTEXT_AUDIT.md]", file=sys.stderr)
    return 1 if window_pins else 0


if __name__ == "__main__":
    sys.exit(main())
