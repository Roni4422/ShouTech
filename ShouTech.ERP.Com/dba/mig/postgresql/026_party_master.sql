CREATE TABLE IF NOT EXISTS parties (
    party_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    party_code varchar(80) NOT NULL,
    party_kind char(1) NOT NULL CHECK (party_kind IN ('C', 'S', 'B')),
    name_en varchar(250) NOT NULL CHECK (btrim(name_en) <> ''),
    name_ar varchar(250),
    group_code varchar(80),
    tax_number varchar(100),
    commercial_registration varchar(100),
    credit_limit numeric(20,6) NOT NULL DEFAULT 0 CHECK (credit_limit >= 0),
    credit_days integer NOT NULL DEFAULT 0 CHECK (credit_days >= 0),
    price_tier varchar(50),
    gl_account_code varchar(100),
    phone varchar(80),
    mobile varchar(80),
    email varchar(250),
    address varchar(1000),
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(100),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(100),
    updated_at timestamptz,
    UNIQUE (company_id, party_kind, party_code)
);

CREATE INDEX IF NOT EXISTS ix_parties_company_kind_active
    ON parties(company_id, party_kind, is_active, is_deleted);

CREATE INDEX IF NOT EXISTS ix_parties_company_name
    ON parties(company_id, lower(name_en));

CREATE INDEX IF NOT EXISTS ix_parties_company_tax
    ON parties(company_id, tax_number)
    WHERE tax_number IS NOT NULL;
